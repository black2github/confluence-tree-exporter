# app/version.py
#
# Версия бандла confluence-tree-exporter (2026-08-07).
#
# Проблема: коллеги работают с копиями бандла на двух контурах и по журналу не
# видят, что запущена неактуальная версия. Решение двухслойное:
#   • VERSION — человекочитаемый номер; поднимается ВРУЧНУЮ при каждой сборке
#     пакета для команды (собрали очередную версию → увеличили номер);
#   • отпечаток исходников — SHA-256 по составу всех *.py пакета app/,
#     считается автоматически при каждом запуске: ЛЮБОЕ изменение любого
#     файла меняет отпечаток, даже если номер поднять забыли.
# Обе величины печатаются при старте утилит (экспорт и critic): совпадение
# номера И отпечатка на внутреннем и внешнем контуре = одна и та же версия.
#
# Переводы строк нормализуются перед хешированием (CRLF→LF): перенос файлов
# между контурами/ОС не должен менять отпечаток при неизменном содержимом.

import hashlib
from pathlib import Path

VERSION = "1.9.0"

# Коммит канона, из которого собрана поставка: подставляется сборщиком
# (app/scripts/build_bundle.py) при раскладке бандла. В самом каноне пусто — это
# дерево разработки, а не поставка. Отпечаток исходников отвечает на вопрос
# «одинаковы ли две копии пакета», штамп — на вопрос «из чего пакет собран»:
# деревья канона и поставки разного состава, их отпечатки несравнимы.
BUILD_FROM = "8a0b2875"


def source_fingerprint() -> str:
    """Отпечаток состава исходников: SHA-256 (первые 8 hex) по всем *.py
    пакета app/ — имена файлов + содержимое, отсортированно и стабильно."""
    root = Path(__file__).resolve().parent
    h = hashlib.sha256()
    for p in sorted(root.rglob("*.py"), key=lambda x: x.relative_to(root).as_posix()):
        if "__pycache__" in p.parts:
            continue
        h.update(p.relative_to(root).as_posix().encode("utf-8"))
        h.update(b"\0")
        h.update(p.read_bytes().replace(b"\r\n", b"\n"))
        h.update(b"\0")
    return h.hexdigest()[:8]


def banner(tool: str) -> str:
    """Строка версии для печати при старте утилиты."""
    line = f"{tool}: версия {VERSION}, отпечаток исходников {source_fingerprint()}"
    return f"{line}, из канона {BUILD_FROM}" if BUILD_FROM else line
